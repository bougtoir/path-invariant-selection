"""Reference audit for manuscript_source_EA.md: cite<->reference matching and Crossref metadata check.

Writes EA_REFERENCE_AUDIT.md. Exit code 1 on any failure.
"""
import glob, json, os, re, sys, unicodedata
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..")
src = open(os.path.join(ROOT, "manuscript_source_EA.md"), encoding="utf-8").read()
body, refs_block = src.split("## References", 1)
refs_block = refs_block.split("## Figure Captions")[0]
tables = "".join(open(f, encoding="utf-8").read() for f in sorted(glob.glob(os.path.join(ROOT, "tables", "EA", "Table*.md"))))
text = body.split("## Abstract", 1)[1] + "\n" + tables
refs = [l.strip() for l in refs_block.strip().splitlines() if l.strip()]
CR = {os.path.basename(f)[:-5].lower(): f for f in glob.glob(os.path.join(ROOT, "data", "raw", "crossref", "*.json"))}


def norm(s):
    s = re.sub(r"[\u2010-\u2015\u2018\u2019]", lambda m: "'" if m.group(0) in "\u2018\u2019" else " ", s)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def parse_ref(r):
    m = re.match(r"(.+?) \((\d{4})\)\. (.+)", r)
    authors, year, rest = m.group(1), m.group(2), m.group(3)
    authors = re.sub(r" \(Eds?\.\)\.?$", "", authors)
    if authors.startswith("American Educational Research Association"):
        surnames = ["American Educational Research Association", "x", "y"]
    else:
        surnames = [a.split(",")[0].strip() for a in re.split(r", (?=[A-Za-z][A-Za-z'\-]+, [A-Za-z]\.)|, & |& ", authors)]
        surnames = [s for s in surnames if s and not re.match(r"^[A-Za-z]\.", s)]
    doi = re.search(r"https://doi\.org/(\S+)$", r)
    return dict(raw=r, surnames=surnames, year=year, rest=rest, doi=doi.group(1) if doi else None)


P = [parse_ref(r) for r in refs]
fail = []
lines = ["# EA_REFERENCE_AUDIT_FINAL", "", "Generated by `scripts/audit_references_EA.py` from `manuscript_source_EA.md` and `tables/EA/`.", "",
         f"References listed: {len(P)}", ""]
# 1. alphabetical order
keys = [[norm(x) for x in p["surnames"]] + [p["year"]] for p in P]
lines.append(f"- Alphabetical order: {'PASS' if keys == sorted(keys) else 'FAIL'}")
if keys != sorted(keys):
    fail.append("order")
# 2. each reference cited
uncited = []
for p in P:
    s = p["surnames"]
    if len(s) == 1:
        a = re.escape(s[0])
    elif len(s) == 2:
        a = re.escape(s[0]) + r" (?:&|and) " + re.escape(s[1])
    else:
        a = re.escape(s[0]) + r" et al\."
    alias = r"|AERA et al\." if s[0].startswith("American") else ""
    pat = r"(?:" + a + alias + r")(?:'s)?,? \(?(?:\d{4}, )*" + p["year"]
    p["cited"] = bool(re.search(pat, text))
    if not p["cited"]:
        uncited.append(p["raw"][:60])
lines.append(f"- Every reference cited in text or tables: {'PASS' if not uncited else 'FAIL ' + str(uncited)}")
fail += uncited
# 3. every citation has a reference
cites = set()
for m in re.finditer(r"([A-Z][A-Za-z\-]+(?: (?:&|and) [A-Z][A-Za-z\-]+| et al\.)?)(?:'s)?,? \(?((?:\d{4}, )*\d{4})", text):
    for y in m.group(2).split(", "):
        cites.add((m.group(1), y))
orphans = []
for name, y in sorted(cites):
    first = name.split(" ")[0]
    if name.startswith(("AERA", "Association")):
        first = "American"
    ok = any(p["year"] == y and p["surnames"][0].split(" ")[0] == first for p in P)
    if not ok:
        orphans.append(f"{name} {y}")
lines.append(f"- Every citation matched to a reference ({len(cites)} distinct author-year citations): {'PASS' if not orphans else 'FAIL ' + str(orphans)}")
fail += orphans
# 4. Crossref metadata
lines += ["", "## Crossref verification (DOI references)", "", "| Reference | Year | Vol(Issue) | First page | Title | 1st author | Author count |", "|---|---|---|---|---|---|---|"]
for p in P:
    if not p["doi"]:
        continue
    f = CR.get(p["doi"].lower().replace("/", "_"))
    if not f:
        lines.append(f"| {p['surnames'][0]} ({p['year']}) | NO CROSSREF FILE | | | | | |"); fail.append(p["doi"]); continue
    m = json.load(open(f))["message"]
    yr = str((m.get("published-print") or m.get("published") or m.get("issued"))["date-parts"][0][0])
    vi = re.search(r"\*(\d+)\*(?:\(([^)]+)\))?", p["rest"])
    pg = re.search(r", (?:Article )?([A-Za-z]*\d+)(?:–\d+)?\. https", p["rest"])
    ct = norm(re.sub(r"^Focus Article: ", "", m["title"][0])); t_ok = ct[:35] in norm(p["rest"])
    au = m.get("author", []) or m.get("editor", [])
    n_ok = len(au) == len(p["surnames"]) or p["surnames"][0].startswith("American")
    fa_ok = bool(au) and norm(au[0].get("family", "")) == norm(p["surnames"][0])
    v_ok = (not m.get("volume")) or (vi and vi.group(1) == m.get("volume") and (not m.get("issue") or (vi.group(2) or "").replace("–", "-") == m["issue"]))
    fp = (m.get("page") or m.get("article-number") or "").split("-")[0]
    p_ok = (not fp) or (pg and pg.group(1) == fp)
    res = [yr == p["year"], v_ok, p_ok, t_ok, fa_ok, n_ok]
    lines.append(f"| {p['surnames'][0]} ({p['year']}) | {'OK' if res[0] else 'MISMATCH ' + yr} | {'OK' if v_ok else 'MISMATCH'} | {'OK' if p_ok else 'MISMATCH ' + fp} | {'OK' if t_ok else 'CHECK'} | {'OK' if fa_ok else 'MISMATCH'} | {'OK' if n_ok else 'MISMATCH %d' % len(au)} |")
    if not all(res):
        fail.append(p["doi"])
lines += ["", "## Non-DOI references (books/chapters)", ""]
for p in P:
    if not p["doi"]:
        lines.append(f"- {p['raw']}")
lines += ["", "Books: Zwick (2017) and the Moss et al. (2008) volume confirmed via Open Library / Crossref records archived in `data/raw/`; Messick (1989), Bourdieu (1986), Collins (1979), Millsap (2011), Popkin (1991), Posselt (2016), Stevens (2007) and the 2014 *Standards* are standard bibliographic records carried over from the SHE-version audit (REFERENCE_AUDIT.md) or canonical citations; no Crossref DOI exists for them.",
          "", f"## Result: {'PASS' if not fail else 'FAIL: ' + '; '.join(fail)}"]
import requests
doi_rows, doi_bad = [], []
for p in P:
    if p.get("doi"):
        try:
            r = requests.head("https://doi.org/" + p["doi"], allow_redirects=False, timeout=30)
            code, loc = r.status_code, r.headers.get("Location", "")
        except Exception as exc:
            code, loc = "ERR", str(exc)[:60]
        if code not in (301, 302, 303, 307, 308) or "doi.org" in loc:
            doi_bad.append(p["doi"])
        doi_rows.append(f"| {p['surnames'][0]} ({p['year']}) | {p['doi']} | {code} | {loc[:80]} |")
fail += doi_bad
ids = [(p["surnames"][0], p["year"], tuple(p["surnames"]) if len(p["surnames"]) <= 2 else "et al.") for p in P]
dups = sorted({str(i) for i in ids if ids.count(i) > 1})
fail += dups
ri = [i for i, l in enumerate(lines) if l.startswith("## Result")][0]
lines[ri] = f"## Result: {'PASS' if not fail else 'FAIL: ' + '; '.join(map(str, fail))}"
lines[ri:ri] = ["## DOI resolution (https://doi.org, redirect not followed; registered DOI -> 30x to publisher)", "",
                "| Reference | DOI | HTTP | Redirect target |", "|---|---|---|---|"] + doi_rows + [""]
lines[2:2] = ["## Exact counts", "", f"- References listed: {len(P)}",
              f"- References with DOI: {len(doi_rows)}; resolving at doi.org: {len(doi_rows) - len(doi_bad)}",
              f"- References without DOI (books/chapters, verified against publisher/catalog record): {len(P) - len(doi_rows)}",
              f"- Distinct in-text/table author-year citations: {len(cites)}",
              f"- Uncited references: {len(uncited)}", f"- Unmatched (orphan) citations: {len(orphans)}",
              f"- Ambiguous author-year keys (a citation matching more than one reference): {len(dups)}", ""]
open(os.path.join(ROOT, "EA_REFERENCE_AUDIT_FINAL.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(l for l in lines if l.startswith("-") or "MISMATCH" in l or "CHECK" in l or "Result" in l or "NO CROSSREF" in l))
sys.exit(1 if fail else 0)
